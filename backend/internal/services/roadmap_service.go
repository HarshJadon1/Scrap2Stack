func (s *roadmapService) GenerateAIRoadmap(ctx context.Context, projectID string) (*models.Roadmap, []models.RoadmapItem, error) {
	pID, err := primitive.ObjectIDFromHex(projectID)
	if err != nil {
		return nil, nil, err
	}
	project, err := s.projectRepo.GetByID(ctx, pID)
	if err != nil {
		return nil, nil, err
	}

	roadmap := &models.Roadmap{
		ProjectID:     pID,
		Title:         "AI Generated Roadmap",
		Description:   "An optimized revival roadmap generated by ScrapAI for " + project.Name,
		GeneratedByAI: true,
		CreatedAt:     time.Now(),
		UpdatedAt:     time.Now(),
	}

	err = s.roadmapRepo.Create(ctx, roadmap)
	if err != nil {
		return nil, nil, err
	}

	phases := []models.RoadmapItem{
		{
			RoadmapID:       roadmap.ID,
			Title:           "Phase 1: Project Audit & Environment Setup",
			Description:     "Clone repository, verify existing build, and audit dependencies.",
			Order:           1,
			Status:          models.RoadmapNotStarted,
			RequiredSkills:  []string{"Git", "Docker"},
			EstimatedEffort: "3 days",
		},
		{
			RoadmapID:       roadmap.ID,
			Title:           "Phase 2: Core Refactoring",
			Description:     "Update legacy dependencies and fix critical bugs identified in analysis.",
			Order:           2,
			Status:          models.RoadmapNotStarted,
			RequiredSkills:  project.Technologies,
			EstimatedEffort: "1 week",
		},
		{
			RoadmapID:       roadmap.ID,
			Title:           "Phase 3: Feature Parity & MVP",
			Description:     "Complete the primary unfinished feature set for MVP release.",
			Order:           3,
			Status:          models.RoadmapNotStarted,
			RequiredSkills:  project.RequiredSkills, // This might need mapping from models.RequiredSkill to string
			EstimatedEffort: "2 weeks",
			Milestone:       true,
		},
	}

	for i := range phases {
		s.roadmapRepo.AddItem(ctx, &phases[i])
	}

	return roadmap, phases, nil
}
